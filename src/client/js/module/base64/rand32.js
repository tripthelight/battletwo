// 0 ~ 2³²-1 범위의 "랜덤한 32비트 정수(uint32) 생성"

/**
 * 0 ~ 2³²-1 범위의 "랜덤한 32비트 정수(uint32) 생성"
  - Math.random() : 0 이상 1 미만의 실수 난수
  - * 0x100000000 : 0x100000000 = 2³²(= 4,294,967,296) 이라서 범위를 0 ~ (2³²-1.xxx) 로 키움
  - >>> 0 : "0으로 unsigned right shift" → 자바스크립트의 값을 32비트 부호 없는 정수(uint32) 로 강제 변환합니다(소수점도 잘려서 정수가 됨).
 * 반환값 범위: 0 ~ 4,294,967,295
 * 타입은 JS에서 여전히 number지만, 값은 uint32 범위로 맞춰집니다.
 * >>> 0는 Math.floor(...) 역할도 같이 하면서(소수점 제거) 32비트로 맞춘다고 보면 됩니다.
*/
// 난수 생성기
export default () => (Math.random() * 0x100000000) >>> 0;
